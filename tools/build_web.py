#!/usr/bin/env python3
"""Builds the firmware web panel headers from the HTML sources in web/.

  python tools/build_web.py          regenerate Mochi_EN/Mochi_html.h and Mochi_TR/Mochi_html.h
  python tools/build_web.py --check  exit 1 if a header doesn't match its HTML source

Edit web/index_en.html or web/index_tr.html, never the headers.
"""
import gzip
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGETS = {
    "web/index_en.html": "Mochi_EN/Mochi_html.h",
    "web/index_tr.html": "Mochi_TR/Mochi_html.h",
}


def render(src: str) -> str:
    gz = gzip.compress((ROOT / src).read_bytes(), 9, mtime=0)
    rows = ",\n  ".join(", ".join("0x%02X" % b for b in gz[i:i + 16]) for i in range(0, len(gz), 16))
    return (
        "// =====================================================================\n"
        f"// Web panel, gzip-compressed. Generated by tools/build_web.py from {src}.\n"
        "// Do not edit by hand.\n"
        "// =====================================================================\n"
        "#pragma once\n#include <Arduino.h>\n\n"
        f"const uint8_t INDEX_HTML_GZ[] PROGMEM = {{\n  {rows},\n}};\n"
        f"const size_t INDEX_HTML_GZ_LEN = {len(gz)};\n"
    )


def header_html(dst: str) -> bytes:
    """Decompresses the HTML stored in a header (gzip output differs between zlib builds, the HTML doesn't)."""
    text = (ROOT / dst).read_text()
    data = bytes(int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})", text.split("PROGMEM", 1)[1]))
    length = int(re.search(r"INDEX_HTML_GZ_LEN = (\d+)", text).group(1))
    if len(data) != length:
        raise ValueError(f"{dst}: INDEX_HTML_GZ_LEN is {length}, array has {len(data)} bytes")
    return gzip.decompress(data)


def main(argv) -> int:
    if "--check" in argv:
        stale = [dst for src, dst in TARGETS.items() if header_html(dst) != (ROOT / src).read_bytes()]
        for dst in stale:
            print(f"{dst} is out of date; run: python tools/build_web.py")
        return 1 if stale else 0
    for src, dst in TARGETS.items():
        (ROOT / dst).write_text(render(src))
        print(f"{src} -> {dst}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
